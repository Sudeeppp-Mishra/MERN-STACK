// Comparison Operator '<', '>', '<=', '>=', '==', '!='
console.log(3>2) // true
console.log(3<2) // false
console.log(3==2) // false -> for comparing values only and auto typecasts
console.log(3!=2) // true
console.log(3>=3) // true
console.log(3<=2) // false
console.log(3===3) // true -> for comparing value and also type strictly

// Logical Operator '&&', '||', '!'
console.log(!true) // false
console.log(true && false && true && true) // false
console.log(true || false || false) // true